export interface LocalizedResolutionResult {
  text: string;
  languageUsed: LanguageCode;
  isFallback: boolean;
  missingNotice: string | null;
  availableLanguages: LanguageCode[];
}

/**
 * Phase 9E — Honest Language Fallback Resolver
 * Never silently displays English while claiming content is translated.
 * If the requested language is missing, returns `isFallback: true` and an explicit
 * "Translation not available" notice so the UI can display a transparent badge/switch.
 */
export function resolveLocalizedTextWithNotice(
  translations: Partial<Record<LanguageCode, string>> | undefined,
  requestedLang: LanguageCode,
  englishDefault: string
): LocalizedResolutionResult {
  const map: Partial<Record<LanguageCode, string>> = {
    en: englishDefault,
    ...(translations || {}),
  };

  const availableLanguages = (Object.keys(map) as LanguageCode[]).filter(
    (k) => typeof map[k] === 'string' && map[k]!.trim().length > 0
  );

  const direct = map[requestedLang];
  if (typeof direct === 'string' && direct.trim().length > 0) {
    return {
      text: direct,
      languageUsed: requestedLang,
      isFallback: false,
      missingNotice: null,
      availableLanguages,
    };
  }

  const noticeKey: CoreSupportedLanguage = CORE_SUPPORTED_LANGUAGES.includes(
    requestedLang as CoreSupportedLanguage
  )
    ? (requestedLang as CoreSupportedLanguage)
    : 'en';

  return {
    text: englishDefault,
    languageUsed: 'en',
    isFallback: requestedLang !== 'en',
    missingNotice:
      requestedLang !== 'en' ? TRANSLATION_UNAVAILABLE_NOTICE[noticeKey] : null,
    availableLanguages,
  };
}

